#!/usr/bin/env python3
"""Check which planned fault rules have the trend data they need.

Usage:
    python3 tools/gap_report.py <point_tags.csv> <out.md>

For each rule, it lists the points the rule reads and counts, across all
equipment of that family, how many exist and how many are trended. A rule can
still run on live values without history, but it then has no backfill and the
charts have nothing to show, so missing trends are listed as gaps to fix in
the station.
"""
import csv
import sys
from collections import defaultdict

# family -> [(rule, [point names the rule needs])]
RULES = {
    "ahu": [
        ("Heating and cooling at the same time", ["Chwv", "HeatDmd", "EDHStg1Call"]),
        ("Supply air temp not reaching setpoint", ["SATmp", "SATmpSP", "FnSts"]),
        ("Economiser not working / should be economising", ["Econ", "OATmp", "RATmp", "OAEnth", "EnthalpySP"]),
        ("Duct static pressure not reaching setpoint", ["SADp", "SADpSP", "SAFSpd"]),
        ("Fan commanded but not running (or the reverse)", ["FnCmd", "FnSts"]),
        ("Running outside scheduled hours", ["FnSts", "AHrsCmd", "OptStartCmd"]),
        ("Temperature sensor drift (SA/RA/OA cross-check)", ["SATmp", "RATmp", "OATmp", "Chwv", "Econ"]),
        ("High zone CO2 / ventilation", ["ZnCO2", "ZnCO2_High", "Econ"]),
        ("Chilled water valve saturated (100% with high SAT)", ["Chwv", "SATmp", "SATmpSP"]),
    ],
    "vav": [
        ("Zone temp out of band", ["RmT_UnitSel", "SpRmT_UnitSel"]),
        ("Airflow not tracking setpoint", ["AbsAirFlow_UnitSel", "SpAbsAirFlow_UnitSel"]),
        ("Damper stuck or hunting", ["DamperDemand", "Damper_Pos"]),
        ("Reheat on while cooling", ["Heater1State", "Heater2State", "CoolingDemand"]),
        ("Rogue zone driving the AHU", ["CoolingDemand", "DamperDemand"]),
    ],
    "chiller": [
        ("Compressor short cycling", ["CH1_COMP1", "CH1_COMP2"]),
        ("Pump commanded but not running", ["CHWP1_CMD", "CHWP1_STS", "CHWP2_CMD", "CHWP2_STS"]),
        ("CHW diff pressure not reaching setpoint", ["CH1_Dp", "ChwDpSp", "CHWP1SPD"]),
        ("Staging hunting", ["CH_Stage_0", "CH_Stage_1", "CH_Stage_2"]),
        ("Bypass open with plant running", ["Bypass", "CH1_STS"]),
    ],
    "chillerHli": [
        ("Leaving CHW temp off setpoint", ["LEAVING$20CHILLED$20LIQ$20TEMP", "REMOTE$20COOLING$20SETP"]),
        ("Low chilled water delta-T", ["ENTERING$20CHILLED$20LIQ$20TEMP", "LEAVING$20CHILLED$20LIQ$20TEMP"]),
        ("Compressor load / lockout trend", ["SYS$201$20COMP$20PCT$20FLA", "SYS$202$20COMP$20PCT$20FLA",
                                            "SYS$201$20LOCKOUT", "SYS$202$20LOCKOUT"]),
    ],
    "ac": [
        ("Fan commanded but not running", ["FnCmd", "FnSts"]),
        ("Running outside scheduled hours", ["FnSts", "SchedSel"]),
        ("Zone temp out of band", ["ZnTmp", "ZnTmpSP"]),
    ],
    "ef": [
        ("Fan commanded but not running", ["FnCmd", "FnSts"]),
        ("Running outside scheduled hours", ["FnSts", "SchedSel"]),
    ],
}


def main(src, dst):
    rows = list(csv.DictReader(open(src)))
    have = defaultdict(lambda: [0, 0])  # (family, point) -> [exists, trended]
    equip_count = defaultdict(set)
    eq = {e["id"]: e["family"] for e in csv.DictReader(open(src.replace("point_tags.csv", "equipment.csv")))}
    for r in rows:
        fam = eq.get(r["equipRef"])
        if not fam:
            continue
        equip_count[fam].add(r["equipRef"])
        k = (fam, r["point"])
        have[k][0] += 1
        have[k][1] += bool(r["history"])

    lines = ["# Trend coverage for planned fault rules", "",
             "Generated by `tools/gap_report.py` from the station backup. "
             "\"Trended\" means the point has an enabled history extension in the supervisor.", ""]
    todo = defaultdict(set)
    for fam, rules in RULES.items():
        n = len(equip_count[fam])
        lines += [f"## {fam} ({n} units)", "", "| Rule | Status | Points (exist / trended of %d) |" % n, "|---|---|---|"]
        for rule, pts in rules:
            cells, ok = [], True
            for p in pts:
                e, t = have.get((fam, p), [0, 0])
                cells.append(f"`{p.replace('$20', ' ')}` {e}/{t}")
                if e and t < e:
                    ok = False
                    todo[fam].add(p)
            status = "Ready" if ok else "Needs trends"
            lines.append(f"| {rule} | {status} | {'; '.join(cells)} |")
        lines.append("")
    lines += ["## Trends to add in the station", "",
              "Adding these history extensions (COV for booleans, 5 min interval for numerics) "
              "gives every rule above its data.", ""]
    for fam, pts in todo.items():
        for p in sorted(pts):
            e, t = have[(fam, p)]
            lines.append(f"- **{fam}** `{p.replace('$20', ' ')}`: {e - t} of {e} not trended")
    open(dst, "w").write("\n".join(lines) + "\n")
    print(f"wrote {dst}; {sum(len(v) for v in todo.values())} point types need trends")


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
